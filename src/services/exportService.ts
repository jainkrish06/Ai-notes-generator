import { jsPDF } from 'jspdf';
import { NoteDocument } from '../types/note';

// Download text file utility
export function downloadTextFile(filename: string, content: string, mimeType = 'text/plain') {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// Export Note as Markdown (.md)
export function exportToMarkdown(note: NoteDocument): void {
  const safeTitle = (note.title || 'Note').replace(/[^a-zA-Z0-9_-]/g, '_');
  const filename = `${safeTitle}.md`;

  const header = `---
title: "${note.title}"
subject: "${note.subject}"
educationLevel: "${note.educationLevel}"
noteType: "${note.noteType}"
exportedAt: "${new Date().toISOString()}"
generator: "NoteMind AI"
---

`;

  const fullContent = header + note.content;
  downloadTextFile(filename, fullContent, 'text/markdown');
}

// Export Note as Plain Text (.txt)
export function exportToPlainText(note: NoteDocument): void {
  const safeTitle = (note.title || 'Note').replace(/[^a-zA-Z0-9_-]/g, '_');
  const filename = `${safeTitle}.txt`;

  // Strip basic markdown syntax for a clean text file
  const plainBody = note.content
    .replace(/^#+\s+/gm, '') // Remove heading markers
    .replace(/\*\*(.*?)\*\*/g, '$1') // Remove bold
    .replace(/\*(.*?)\*/g, '$1') // Remove italics
    .replace(/`{3}[\s\S]*?`{3}/g, (match) => match.replace(/`{3}/g, '')) // Remove code fence markers
    .replace(/`([^`]+)`/g, '$1') // Remove inline backticks
    .replace(/^\s*>\s+/gm, '  | ') // Convert blockquotes
    .replace(/\[(.*?)\]\(.*?\)/g, '$1'); // Clean links

  const header = `${note.title.toUpperCase()}\nSubject: ${note.subject} | Level: ${note.educationLevel}\nGenerated by NoteMind AI on ${new Date().toLocaleDateString()}\n${'='.repeat(60)}\n\n`;

  downloadTextFile(filename, header + plainBody, 'text/plain');
}

// Export Note as a beautifully styled PDF with page numbers and headers
export function exportToPdf(note: NoteDocument): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 45;
  const contentWidth = pageWidth - margin * 2;
  let currentY = margin;

  // Header banner
  doc.setFillColor(30, 41, 59); // deep slate/navy #1e293b
  doc.rect(margin, currentY, contentWidth, 5, 'F');
  currentY += 20;

  // Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42); // slate-900

  const titleLines = doc.splitTextToSize(note.title || 'Study Notes', contentWidth);
  doc.text(titleLines, margin, currentY);
  currentY += titleLines.length * 22 + 4;

  // Metadata Subtitle
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139); // slate-500
  const metaText = `Subject: ${note.subject || 'General'}  •  Level: ${note.educationLevel.toUpperCase()}  •  Type: ${note.noteType.toUpperCase()}  •  Date: ${new Date(note.updatedAt || Date.now()).toLocaleDateString()}`;
  doc.text(metaText, margin, currentY);
  currentY += 16;

  // Thin separator line
  doc.setDrawColor(226, 232, 240); // slate-200
  doc.setLineWidth(0.8);
  doc.line(margin, currentY, pageWidth - margin, currentY);
  currentY += 18;

  // Body content parsing
  const rawLines = note.content.split('\n');

  doc.setTextColor(30, 41, 59); // slate-800

  for (let i = 0; i < rawLines.length; i++) {
    const line = rawLines[i].trimEnd();

    // Check if we need a new page
    if (currentY > pageHeight - margin - 30) {
      doc.addPage();
      currentY = margin;
    }

    if (!line.trim()) {
      currentY += 8;
      continue;
    }

    // Heading 1 (#)
    if (line.startsWith('# ')) {
      // Skip if it duplicates the document title at the top
      if (i === 0) continue;
      currentY += 10;
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(15);
      doc.setTextColor(15, 23, 42);
      const text = line.replace(/^#\s+/, '');
      const wrapped = doc.splitTextToSize(text, contentWidth);
      doc.text(wrapped, margin, currentY);
      currentY += wrapped.length * 18 + 6;
      continue;
    }

    // Heading 2 (##)
    if (line.startsWith('## ')) {
      currentY += 8;
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(13);
      doc.setTextColor(30, 41, 59);
      const text = line.replace(/^##\s+/, '');
      const wrapped = doc.splitTextToSize(text, contentWidth);
      doc.text(wrapped, margin, currentY);
      currentY += wrapped.length * 16 + 4;
      continue;
    }

    // Heading 3 (###)
    if (line.startsWith('### ')) {
      currentY += 6;
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(51, 65, 85);
      const text = line.replace(/^###\s+/, '');
      const wrapped = doc.splitTextToSize(text, contentWidth);
      doc.text(wrapped, margin, currentY);
      currentY += wrapped.length * 14 + 3;
      continue;
    }

    // Blockquote (>)
    if (line.startsWith('>')) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(10);
      doc.setTextColor(71, 85, 105);
      const text = line.replace(/^>\s*/, '');
      const wrapped = doc.splitTextToSize(text, contentWidth - 16);

      // Light background callout box
      const boxHeight = wrapped.length * 13 + 8;
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, currentY - 8, contentWidth, boxHeight, 'F');
      doc.setFillColor(99, 102, 241); // indigo border
      doc.rect(margin, currentY - 8, 3, boxHeight, 'F');

      doc.text(wrapped, margin + 10, currentY);
      currentY += boxHeight + 4;
      continue;
    }

    // Bullet points (- or *)
    if (line.match(/^[\*\-]\s+/)) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(51, 65, 85);
      const text = line.replace(/^[\*\-]\s+/, '').replace(/\*\*(.*?)\*\*/g, '$1');
      const wrapped = doc.splitTextToSize(text, contentWidth - 14);
      doc.text('•', margin + 2, currentY);
      doc.text(wrapped, margin + 14, currentY);
      currentY += wrapped.length * 13 + 3;
      continue;
    }

    // Regular paragraph text
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(30, 41, 59);
    // Strip bold asterisks for clean text formatting in jsPDF standard fonts
    const cleanLine = line.replace(/\*\*(.*?)\*\*/g, '$1');
    const wrapped = doc.splitTextToSize(cleanLine, contentWidth);
    doc.text(wrapped, margin, currentY);
    currentY += wrapped.length * 13 + 3;
  }

  // Add Page Numbers and Footer to all pages
  const totalPages = doc.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184); // slate-400

    // Footer divider line
    doc.setDrawColor(241, 245, 249);
    doc.line(margin, pageHeight - 30, pageWidth - margin, pageHeight - 30);

    // Footer text
    doc.text('Generated with NoteMind AI', margin, pageHeight - 18);
    doc.text(`Page ${p} of ${totalPages}`, pageWidth - margin - 50, pageHeight - 18);
  }

  const safeTitle = (note.title || 'NoteMind_Notes').replace(/[^a-zA-Z0-9_-]/g, '_');
  doc.save(`${safeTitle}.pdf`);
}
